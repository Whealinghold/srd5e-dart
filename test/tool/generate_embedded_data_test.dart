import 'dart:io';

import 'package:test/test.dart';

import '../../tool/generate_embedded_data.dart';
import '../architecture/checks/lib_boundaries.dart';
import '../architecture/support/package_root.dart';
import '../architecture/support/source_set.dart';

/// Unit tests over the embedded-data generator core
/// (doc/specs/content-schema-and-decoder.md FR-120 to FR-122) and its wiring
/// rules: one library per data file with the verbatim attribution header, a
/// lower-camel-case constant holding the text character for character, a
/// byte-stable ordinal-order output with the index of FR-122, and the
/// `ArgumentError`s of FR-121. The pairing test runs the real `dart format`
/// over generated output so the drift check (FR-123) and the format gate can
/// never fight over a generated byte.
const Timeout _budget = Timeout(Duration(seconds: 10));

/// A text holding every escape that matters: dollar, quote, backslash, tab,
/// carriage return, the typographic apostrophe kept as is, two astral
/// characters kept as is, three control characters, and two line breaks (the
/// last line empty).
const String _nasty =
    'dollar\$ quote\' backslash\\ tab\t carriage\rr typographic \u2019 '
    'emoji \u{1F600} gothic \u{10348} '
    'null\x00 unit\x1f del\x7f\nsecond line\n';

/// A short text emitted as one line.
const String _tiny = '{"a": 1}';

/// Extracts the bodies of every single-quoted literal in [libraryText] (the
/// header holds none).
List<String> _literalBodies(String libraryText) {
  final matches = RegExp("'((?:\\\\.|[^'\\\\])*)'").allMatches(libraryText);
  return [for (final match in matches) match.group(1)!];
}

/// The test-side unescaper: evaluates the escapes of one literal body, the
/// inverse of the generator's escaper.
String _unescape(String body) {
  final buffer = StringBuffer();
  var i = 0;
  while (i < body.length) {
    if (body[i] != r'\') {
      buffer.write(body[i]);
      i++;
      continue;
    }
    final escape = body[i + 1];
    switch (escape) {
      case '\\':
        buffer.write(r'\');
      case '\$':
        buffer.write(r'$');
      case "'":
        buffer.write("'");
      case 'n':
        buffer.write('\n');
      case 'r':
        buffer.write('\r');
      case 't':
        buffer.write('\t');
      case 'b':
        buffer.write('\b');
      case 'v':
        buffer.write('\v');
      case 'f':
        buffer.write('\f');
      case 'u':
        buffer.writeCharCode(
          int.parse(body.substring(i + 2, i + 6), radix: 16),
        );
      default:
        throw ArgumentError.value(escape, 'escape', 'is not handled');
    }
    i += escape == 'u' ? 6 : 2;
  }
  return buffer.toString();
}

void main() {
  /// Requirement: doc/specs/content-schema-and-decoder.md FR-120, FR-121,
  ///   FR-122 - the generator core's rows: library and constant naming, the
  ///   verbatim header, escaping, determinism, the index, purity and the
  ///   format pairing; doc/specs/content-schema-and-decoder.md FR-124 -
  ///   the generator is not extraction: its core does no I/O and reads no
  ///   PDF, so the purity rows here double as the FR-124 rule.
  /// Path: happy
  group('generateEmbeddedLibraries', timeout: _budget, () {
    /// Requirement: doc/specs/content-schema-and-decoder.md FR-120 - one
    ///   Dart library per data file, at
    ///   `lib/src/content/data/<stem>.dart`, declaring one `const String`.
    /// Path: happy
    test('one library per data file, named for its stem', () {
      final libraries = generateEmbeddedLibraries(const {
        'species.json': _tiny,
        'armor.json': _tiny,
      });

      expect(libraries.keys, [
        'lib/src/content/data/armor.dart',
        'lib/src/content/data/species.dart',
        'lib/src/content/data/embedded_documents.dart',
      ]);
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-120 - the
    ///   constant is the stem in lower camel case plus `Json`
    ///   (`species_extra.json` gives `speciesExtraJson`).
    /// Path: happy
    test('constant name is the lower-camel stem plus Json', () {
      final libraries = generateEmbeddedLibraries(const {
        'species.json': _tiny,
        'species_extra.json': _tiny,
      });

      expect(
        libraries['lib/src/content/data/species.dart'],
        contains('const String speciesJson = '),
      );
      expect(
        libraries['lib/src/content/data/species_extra.dart'],
        contains('const String speciesExtraJson = '),
      );
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-120 - each
    ///   library starts with the two-line header of
    ///   content-licensing-and-notice.md FR-029, verbatim.
    /// Path: happy
    test('every library starts with the FR-029 header, verbatim', () {
      final libraries = generateEmbeddedLibraries(const {'a.json': _tiny});

      expect(embeddedHeaderLines, [
        '// GENERATED from data/srd_5_2_1/. Contains SRD 5.2.1 content.',
        '// Attribution: see NOTICE.md in the package root.',
      ]);
      for (final text in libraries.values) {
        expect(text.split('\n').take(2), embeddedHeaderLines);
      }
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-120 - the
    ///   literal evaluates to exactly the file text: dollar, quote,
    ///   backslash, tab, carriage return, control characters and the
    ///   typographic apostrophe and astral characters (kept as is)
    ///   round-trip through a test-side unescaper.
    /// Path: happy
    test('escaping round-trips every special character', () {
      final libraries = generateEmbeddedLibraries(const {
        'roundtrip.json': _nasty,
      });
      final library = libraries['lib/src/content/data/roundtrip.dart']!;

      final roundTripped = _literalBodies(library).map(_unescape).join();
      expect(roundTripped, _nasty);
      // The typographic apostrophe and the astral characters are content,
      // not escapes: they are kept as is in the emitted source (FR-029
      // fidelity).
      expect(library.contains('\u2019'), isTrue);
      expect(library.contains(r'\u2019'), isFalse);
      expect(library.contains('\u{1F600}'), isTrue);
      expect(library.contains('\u{10348}'), isTrue);
      expect(library.contains(r'\ud83d'), isFalse);
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-120 - a valid
    ///   surrogate pair is one character, kept as is; only a lone surrogate
    ///   (no character form) is escaped.
    /// Path: happy
    test('valid pairs stay as is, lone surrogates are escaped', () {
      const text = 'pair \u{1F600} lone high \ud800 lone low \udc00 end\n';
      final libraries = generateEmbeddedLibraries({'astral.json': text});
      final library = libraries['lib/src/content/data/astral.dart']!;

      expect(library.contains('\u{1F600}'), isTrue);
      expect(library.contains(r'\ud800'), isTrue);
      expect(library.contains(r'\udc00'), isTrue);
      expect(_literalBodies(library).map(_unescape).join(), text);
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-120 - one
    ///   source line per literal line, joined by adjacent literals, so the
    ///   output is a pure function of the text; `\n` endings and one
    ///   trailing newline per file (FR-121).
    /// Path: happy
    test('one source line per literal line, one trailing newline', () {
      final longLine = '${'x' * 70}\n${'y' * 70}\n';
      final libraries = generateEmbeddedLibraries({'lines.json': longLine});
      final library = libraries['lib/src/content/data/lines.dart']!;

      final lines = library.split('\n');
      // Header (2), blank, declaration line, two literal lines, empty last
      // literal shares the line with the semicolon.
      final literalLines = lines
          .where((line) => line.startsWith("    '"))
          .toList();
      expect(literalLines, hasLength(3));
      for (final line in literalLines) {
        expect(line, matches(RegExp(r"^    '(?:\\.|[^'\\])*';?$")));
      }
      for (final text in libraries.values) {
        expect(text.endsWith('\n'), isTrue);
        expect(text.endsWith('\n\n'), isFalse);
        expect(text.contains('\r\n'), isFalse);
      }
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-121 - the
    ///   core is deterministic and byte-stable: the same input gives the
    ///   same output, whatever the map's iteration order.
    /// Path: happy
    test('deterministic across runs and map orders', () {
      final input = {'zulu.json': _tiny, 'alpha.json': _nasty};
      final reordered = {'alpha.json': _nasty, 'zulu.json': _tiny};

      expect(
        generateEmbeddedLibraries(input),
        generateEmbeddedLibraries(input),
      );
      expect(
        generateEmbeddedLibraries(input),
        generateEmbeddedLibraries(reordered),
      );
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-121 - the
    ///   output is in ordinal order of file name.
    /// Path: happy
    test('output is in ordinal order of file name', () {
      final libraries = generateEmbeddedLibraries(const {
        'zulu.json': _tiny,
        'alpha.json': _tiny,
      });

      expect(libraries.keys.toList(), [
        'lib/src/content/data/alpha.dart',
        'lib/src/content/data/zulu.dart',
        'lib/src/content/data/embedded_documents.dart',
      ]);
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-122 - the
    ///   output includes `embedded_documents.dart`, mapping each file stem
    ///   to its JSON constant in ordinal stem order.
    /// Path: happy
    test('the index lists stems in ordinal order over the constants', () {
      final libraries = generateEmbeddedLibraries(const {
        'zulu.json': '{}',
        'alpha.json': '[]',
      });

      expect(
        libraries['lib/src/content/data/embedded_documents.dart'],
        '// GENERATED from data/srd_5_2_1/. Contains SRD 5.2.1 content.\n'
        '// Attribution: see NOTICE.md in the package root.\n'
        '\n'
        "/// The text of `data/srd_5_2_1/alpha.json`, verbatim (FR-120).\n"
        "const String alphaJson = '[]';\n"
        '\n'
        "/// The text of `data/srd_5_2_1/zulu.json`, verbatim (FR-120).\n"
        "const String zuluJson = '{}';\n"
        '\n'
        '/// The embedded documents by file stem\n'
        '/// (content-schema-and-decoder.md FR-122).\n'
        'const Map<String, String> embeddedDocuments = {\n'
        "  'alpha': alphaJson,\n"
        "  'zulu': zuluJson,\n"
        '};\n',
      );
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-122 - with
    ///   no data file the index is empty; FR-121 - empty input gives only
    ///   the index.
    /// Path: unhappy (empty and minimal)
    test('empty input gives only the empty index', () {
      final libraries = generateEmbeddedLibraries(const {});

      expect(libraries, {
        'lib/src/content/data/embedded_documents.dart':
            '// GENERATED from data/srd_5_2_1/. Contains SRD 5.2.1 content.\n'
            '// Attribution: see NOTICE.md in the package root.\n'
            '\n'
            '/// The embedded documents by file stem\n'
            '/// (content-schema-and-decoder.md FR-122).\n'
            'const Map<String, String> embeddedDocuments = {};\n',
      });
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-121 - the
    ///   core is pure: the file defining it imports no `dart:io` and no
    ///   package.
    /// Path: happy
    test('the core imports no dart:io and no package', () {
      final source = File(
        '${findPackageRoot().path}/tool/generate_embedded_data.dart',
      ).readAsStringSync();

      expect(
        RegExp(r"^import\s+'dart:io", multiLine: true).hasMatch(source),
        isFalse,
      );
      expect(
        RegExp(r"^import\s+'package:", multiLine: true).hasMatch(source),
        isFalse,
      );
      expect(
        RegExp(r"^import\s+'dart:io", multiLine: true).hasMatch(
          File(
            '${findPackageRoot().path}/tool/generate_embedded_data_main.dart',
          ).readAsStringSync(),
        ),
        isTrue,
        reason: 'the wrapper reads files; the core must not',
      );
    }, timeout: _budget);

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-120, FR-123
    ///   - the generated literals survive `dart format` byte for byte, so
    ///   the drift check and the format gate never fight over a byte. Runs
    ///   the real formatter over the generated output in a temporary
    ///   directory and requires it to change nothing.
    /// Path: happy
    test('generated output survives dart format byte for byte', () {
      final dir = Directory.systemTemp.createTempSync('srd5e_generated');
      addTearDown(() => dir.deleteSync(recursive: true));
      final longLine = '${'x' * 70}\n${'y' * 70}\n';
      final libraries = generateEmbeddedLibraries({
        'roundtrip.json': _nasty,
        'tiny.json': _tiny,
        'lines.json': longLine,
      });
      final written = <String, String>{};
      for (final MapEntry(key: path, value: text) in libraries.entries) {
        final name = path.split('/').last;
        File('${dir.path}/$name').writeAsStringSync(text);
        written[name] = text;
      }

      final result = Process.runSync(Platform.resolvedExecutable, [
        'format',
        '--set-exit-if-changed',
        dir.path,
      ]);
      expect(
        result.exitCode,
        0,
        reason:
            'dart format would rewrite the generated output:\n'
            '${result.stdout}',
      );
      for (final MapEntry(key: name, value: text) in written.entries) {
        expect(File('${dir.path}/$name').readAsStringSync(), text);
      }
    });
  });

  /// Requirement: doc/specs/content-schema-and-decoder.md FR-121 - the
  ///   `ArgumentError`s over malformed input names and colliding constants.
  /// Path: unhappy (invalid input)
  group('invalid input', () {
    /// Requirement: doc/specs/content-schema-and-decoder.md FR-121 - a name
    ///   that is not `<stem>.json` with `<stem>` matching
    ///   `[a-z][a-z0-9_]*` throws an `ArgumentError` (name and
    ///   invalidValue, never the message).
    /// Path: unhappy (invalid input)
    test('a bad name throws ArgumentError', () {
      const badNames = [
        'Species.json',
        '1species.json',
        '_species.json',
        'species.txt',
        'species.JSON',
        'species.extra.json',
        'species',
        '',
      ];

      for (final name in badNames) {
        final throws = throwsA(
          isA<ArgumentError>()
              .having((error) => error.name, 'name', 'dataFileTexts')
              .having((error) => error.invalidValue, 'invalidValue', name),
        );
        expect(
          () => generateEmbeddedLibraries({name: _tiny}),
          throws,
          reason: '$name must be rejected',
        );
      }
    });

    /// Requirement: doc/specs/content-schema-and-decoder.md FR-121 - two
    ///   names with one lower-camel-case constant throw an `ArgumentError`
    ///   naming the later one in ordinal order.
    /// Path: unhappy (invalid input)
    test('two names with one constant throw ArgumentError', () {
      final collisions = [
        ({'species.json': _tiny, 'species_.json': _tiny}, 'species_.json'),
        (
          {'species_extra.json': _tiny, 'species__extra.json': _tiny},
          // Ordinal order: '_' (0x5f) sorts below 'e' (0x65), so
          // `species__extra.json` is processed first and
          // `species_extra.json` is the offender.
          'species_extra.json',
        ),
      ];

      for (final (input, offender) in collisions) {
        expect(
          () => generateEmbeddedLibraries(input),
          throwsA(
            isA<ArgumentError>()
                .having((error) => error.name, 'name', 'dataFileTexts')
                .having(
                  (error) => error.invalidValue,
                  'invalidValue',
                  offender,
                ),
          ),
        );
      }
    });
  });

  /// Requirement: doc/specs/content-schema-and-decoder.md FR-122 - the index
  ///   is exported from no entry point.
  /// Path: unhappy (state error)
  group('the index stays out of the exported surface', () {
    /// Requirement: doc/specs/content-schema-and-decoder.md FR-122 - the
    ///   index is imported only by `BundledContentSource` and the FR-104
    ///   architecture test and is exported from no entry point; exporting
    ///   an embedded-data library from an entry point is a violation of
    ///   architecture-guardrails.md FR-095 (the check that owns the rule;
    ///   the barrel scan reads type declarations only, so the placement is
    ///   enforced there).
    /// Path: unhappy (state error)
    test('exporting the index from an entry point is flagged', () {
      final violations = checkEmbeddedDataImports(
        SourceSet({
          'lib/srd5e.dart':
              "export 'src/content/data/embedded_documents.dart';\n",
          'lib/src/content/data/embedded_documents.dart': 'const x = 1;\n',
        }),
      );

      expect(violations, hasLength(1));
      expect(violations.single.checkId, 'FR-095');
      expect(violations.single.path, 'lib/srd5e.dart');
      expect(violations.single.line, 1);
    });
  });
}
