/// One of the six abilities that all creatures, characters and monsters, have.
///
/// "All creatures—characters and monsters—have six abilities that measure
/// physical and mental characteristics" ("The Six Abilities", SRD 5.2.1,
/// p. 5). The values are in the order the SRD lists them. The SRD's
/// descriptions and abbreviations are display text and are not held here.
enum Ability {
  /// Strength.
  strength,

  /// Dexterity.
  dexterity,

  /// Constitution.
  constitution,

  /// Intelligence.
  intelligence,

  /// Wisdom.
  wisdom,

  /// Charisma.
  charisma,
}
